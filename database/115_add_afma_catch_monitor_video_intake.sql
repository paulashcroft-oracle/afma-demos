-- Earlier demo builds staged submissions behind a second approval step. The
-- internal demo now relies on the persistent disclosure and a processing
-- clearance queue. Existing sources enter that queue without starting AI
-- processing; only completed sources become selectable review scenarios.
begin
  update afma_cm_video_submissions
     set processing_status = 'AWAITING_IMPORT',
         processing_stage = 'AWAITING_PROJECT_IMPORT',
         progress_percent = 5,
         processing_message = 'The source URL is registered for this project to import when requested. No video bytes are stored and no model call has started.',
         processing_started_at = coalesce(processing_started_at, systimestamp),
         last_progress_at = systimestamp,
         metadata_status = case when metadata_status = 'AWAITING_PROMPT_APPROVAL' then 'NOT_REQUESTED' else metadata_status end
   where input_method = 'URL'
     and processing_status in ('AWAITING_PROMPT_APPROVAL','READY_FOR_ANALYSIS','ANALYSING')
     and rights_confirmed_yn = 'Y'
     and handling_acknowledged_yn = 'Y';

  update afma_cm_video_submissions
     set processing_status = 'ANALYSING',
         processing_stage = 'QUEUED_FOR_ANALYSIS',
         progress_percent = 20,
         processing_message = 'Video bytes are stored in AIDEMODB and queued for the asynchronous analysis worker. No model call has started.',
         processing_started_at = coalesce(processing_started_at, systimestamp),
         last_progress_at = systimestamp,
         metadata_status = case when metadata_status = 'AWAITING_PROMPT_APPROVAL' then 'NOT_REQUESTED' else metadata_status end
   where input_method = 'UPLOAD'
     and processing_status in ('AWAITING_PROMPT_APPROVAL','READY_FOR_ANALYSIS')
     and rights_confirmed_yn = 'Y'
     and handling_acknowledged_yn = 'Y';

  for r in (
    select submission_id
      from afma_cm_video_submissions
     where processing_status in ('AWAITING_IMPORT','ANALYSING')
       and analysis_run_id is null
  ) loop
    afma_cm_video_intake_api.approve_submission(r.submission_id, 'Y');
  end loop;
end;

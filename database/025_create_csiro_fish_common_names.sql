create or replace package body csiro_caab_common_name_api as
  function current_year return number is
  begin
    return to_number(to_char(sysdate, 'YYYY'));
  end current_year;

  procedure upsert_curated(
    p_scientific_name      in varchar2,
    p_common_name          in varchar2,
    p_name_kind            in varchar2,
    p_region_code          in varchar2 default 'NATIONAL',
    p_jurisdiction         in varchar2 default null,
    p_locality             in varchar2 default null,
    p_first_observed_year  in number default 1990,
    p_last_observed_year   in number default null,
    p_season_start_month   in number default null,
    p_season_end_month     in number default null,
    p_source_name          in varchar2 default 'AFMA demo curated alias research',
    p_source_url           in varchar2 default null,
    p_source_confidence    in varchar2 default 'SYNTHETIC',
    p_synthetic_flag       in varchar2 default 'Y',
    p_notes                in varchar2 default null
  ) is
    l_spcode csiro_caab_taxa.spcode%type;
    l_region csiro_caab_fishing_regions%rowtype;
    l_jurisdiction varchar2(40);
    l_last_observed_year number(4);
  begin
    if p_scientific_name is null or p_common_name is null then
      return;
    end if;

    begin
      select spcode
        into l_spcode
        from (
          select spcode,
                 case
                   when coalesce(non_current_flag, 'N') in ('Y', 'T') then 1
                   else 0
                 end non_current_sort
            from csiro_caab_taxa
           where lower(scientific_name) = lower(p_scientific_name)
           order by non_current_sort, spcode
        )
       where rownum = 1;
    exception
      when no_data_found then
        return;
    end;

    begin
      select *
        into l_region
        from csiro_caab_fishing_regions
       where region_code = upper(p_region_code);

      l_jurisdiction := coalesce(upper(p_jurisdiction), l_region.jurisdiction);
    exception
      when no_data_found then
        l_jurisdiction := upper(p_jurisdiction);
    end;

    l_last_observed_year := coalesce(p_last_observed_year, current_year);

    merge into csiro_caab_common_names target
    using (
      select l_spcode spcode,
             trim(p_common_name) common_name,
             csiro_caab_normalize_name(p_common_name) normalized_common_name,
             upper(trim(p_name_kind)) name_kind,
             l_jurisdiction jurisdiction,
             upper(trim(p_region_code)) region_code,
             trim(p_locality) locality,
             p_first_observed_year first_observed_year,
             l_last_observed_year last_observed_year,
             p_season_start_month season_start_month,
             p_season_end_month season_end_month,
             p_source_name source_name,
             p_source_url source_url,
             upper(coalesce(p_source_confidence, 'SYNTHETIC')) source_confidence,
             upper(coalesce(p_synthetic_flag, 'Y')) synthetic_flag,
             'AFMA_CURATED_DEMO' seed_batch,
             p_notes notes
        from dual
    ) source
    on (
      target.spcode = source.spcode
      and target.normalized_common_name = source.normalized_common_name
      and target.name_kind = source.name_kind
      and nvl(target.region_code, '~') = nvl(source.region_code, '~')
      and nvl(target.locality, '~') = nvl(source.locality, '~')
      and nvl(target.first_observed_year, -1) = nvl(source.first_observed_year, -1)
      and nvl(target.last_observed_year, -1) = nvl(source.last_observed_year, -1)
    )
    when matched then
      update set common_name = source.common_name,
                 jurisdiction = source.jurisdiction,
                 season_start_month = source.season_start_month,
                 season_end_month = source.season_end_month,
                 source_name = source.source_name,
                 source_url = source.source_url,
                 source_confidence = source.source_confidence,
                 synthetic_flag = source.synthetic_flag,
                 seed_batch = source.seed_batch,
                 notes = source.notes
    when not matched then
      insert (
        spcode,
        common_name,
        normalized_common_name,
        name_kind,
        jurisdiction,
        region_code,
        locality,
        first_observed_year,
        last_observed_year,
        season_start_month,
        season_end_month,
        source_name,
        source_url,
        source_confidence,
        synthetic_flag,
        seed_batch,
        notes
      ) values (
        source.spcode,
        source.common_name,
        source.normalized_common_name,
        source.name_kind,
        source.jurisdiction,
        source.region_code,
        source.locality,
        source.first_observed_year,
        source.last_observed_year,
        source.season_start_month,
        source.season_end_month,
        source.source_name,
        source.source_url,
        source.source_confidence,
        source.synthetic_flag,
        source.seed_batch,
        source.notes
      );
  exception
    when no_data_found then
      null;
  end upsert_curated;

  procedure rebuild_from_caab_data is
  begin
    delete from csiro_caab_common_names
     where seed_batch in ('CAAB_CURRENT_PRIMARY', 'CAAB_CURRENT_ALT');

    insert into csiro_caab_common_names (
      spcode,
      common_name,
      normalized_common_name,
      name_kind,
      jurisdiction,
      region_code,
      source_name,
      source_url,
      source_confidence,
      synthetic_flag,
      seed_batch,
      notes
    )
    select t.spcode,
           trim(t.common_name),
           csiro_caab_normalize_name(t.common_name),
           'CSIRO_PRIMARY',
           'AU',
           'NATIONAL',
           'CSIRO CAAB workbook COMMON_NAME column',
           'https://www.cmar.csiro.au/data/caab/',
           'CSIRO',
           'N',
           'CAAB_CURRENT_PRIMARY',
           'Directly loaded from the CSIRO CAAB source extract.'
      from csiro_caab_fish_taxa_v t
     where t.common_name is not null
       and csiro_caab_normalize_name(t.common_name) is not null;

    insert into csiro_caab_common_names (
      spcode,
      common_name,
      normalized_common_name,
      name_kind,
      jurisdiction,
      region_code,
      source_name,
      source_url,
      source_confidence,
      synthetic_flag,
      seed_batch,
      notes
    )
    with lists as (
      select spcode,
             regexp_replace(common_names_list, '<[^>]*>', '|') cleaned_list
        from csiro_caab_fish_taxa_v
       where common_names_list is not null
    ),
    parts as (
      select spcode,
             regexp_replace(trim(regexp_substr(cleaned_list, '[^|,;/]+', 1, level)), ' +', ' ') common_name
        from lists
      connect by prior spcode = spcode
             and prior sys_guid() is not null
             and level <= regexp_count(cleaned_list, '[|,;/]') + 1
    ),
    raw_clean_parts as (
      select distinct spcode,
             common_name,
             csiro_caab_normalize_name(common_name) normalized_common_name
        from parts
       where common_name is not null
         and csiro_caab_normalize_name(common_name) is not null
         and length(common_name) <= 200
    ),
    clean_parts as (
      select spcode,
             min(common_name) keep (dense_rank first order by length(common_name), common_name) common_name,
             normalized_common_name
        from raw_clean_parts
       group by spcode,
                normalized_common_name
    )
    select p.spcode,
           p.common_name,
           p.normalized_common_name,
           'CSIRO_ALT',
           'AU',
           'NATIONAL',
           'CSIRO CAAB workbook COMMON_NAMES_LIST column',
           'https://www.cmar.csiro.au/data/caab/',
           'CSIRO',
           'N',
           'CAAB_CURRENT_ALT',
           'Alternative name parsed from CSIRO CAAB COMMON_NAMES_LIST. Source annotations in angle brackets were removed.'
      from clean_parts p
     where not exists (
             select 1
               from csiro_caab_common_names cn
              where cn.spcode = p.spcode
                and cn.normalized_common_name = p.normalized_common_name
           );
  end rebuild_from_caab_data;

  procedure seed_curated_demo_names is
    c_fish_gov constant varchar2(1000) := 'https://fish.gov.au/';
    c_nsw constant varchar2(1000) := 'https://www.fishfiles.com.au/fisheries-and-farms/nsw-fisheries-and-farms/ocean-trap-and-line-fishery';
    c_nt_barra constant varchar2(1000) := 'https://www.fishfiles.com.au/fisheries-and-farms/nt-fisheries-and-farms/wild-barramundi-fishery';

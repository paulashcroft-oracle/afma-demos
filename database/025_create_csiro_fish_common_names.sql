create or replace function csiro_caab_normalize_name(
  p_value in varchar2
) return varchar2 deterministic is
  l_value varchar2(4000);
begin
  l_value := lower(trim(coalesce(p_value, '')));
  l_value := regexp_replace(l_value, '[^[:alnum:]]+', ' ');
  l_value := regexp_replace(trim(l_value), ' +', ' ');
  return nullif(l_value, '');
end csiro_caab_normalize_name;

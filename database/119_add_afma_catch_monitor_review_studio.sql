create or replace package body afma_cm_review_agent_api as
  function actor_name return varchar2 is
  begin
    return coalesce(apex_application.g_user, sys_context('APEX$SESSION','APP_USER'), user);
  end actor_name;

  function h(p_value in varchar2) return varchar2 is
  begin
    return apex_escape.html(p_value);
  end h;

  function a(p_value in varchar2) return varchar2 is
  begin
    return apex_escape.html_attribute(p_value);
  end a;

  procedure add_text(p_html in out nocopy clob, p_text in varchar2) is
  begin
    if p_text is not null then
      dbms_lob.writeappend(p_html, length(p_text), p_text);
    end if;
  end add_text;

  procedure add_line(p_html in out nocopy clob, p_text in varchar2 default null) is
  begin
    add_text(p_html, p_text || chr(10));
  end add_line;

  function fmt_second(p_second in number) return varchar2 is
  begin
    return lpad(trunc(coalesce(p_second, 0) / 60), 2, '0') || ':' ||
           lpad(mod(trunc(coalesce(p_second, 0)), 60), 2, '0');
  end fmt_second;

  function youtube_video_id(p_source_url in varchar2) return varchar2 is
    l_url varchar2(2000) := trim(p_source_url);
    l_id  varchar2(32);
  begin
    if regexp_like(l_url, '^https://youtu\.be/', 'i') then
      l_id := regexp_substr(l_url, 'youtu\.be/([[:alnum:]_-]{11})', 1, 1, 'i', 1);
    elsif regexp_like(l_url, '^https://(www\.|m\.)?youtube\.com/watch([/?]|$)', 'i') then
      l_id := regexp_substr(l_url, '[?&]v=([[:alnum:]_-]{11})', 1, 1, 'i', 1);
    elsif regexp_like(l_url, '^https://(www\.|m\.)?youtube\.com/(shorts|embed|live)/', 'i') then
      l_id := regexp_substr(l_url, '/(shorts|embed|live)/([[:alnum:]_-]{11})', 1, 1, 'i', 2);
    end if;
    return case when regexp_like(l_id, '^[[:alnum:]_-]{11}$') then l_id end;
  end youtube_video_id;

  function session_segment_start(p_review_session_id in number) return number is
    l_start number;
  begin
    select coalesce(mo.source_start_second, o.start_second)
      into l_start
      from afma_cm_review_sessions rs
      join afma_cm_observations o on o.observation_id = rs.observation_id
      left join afma_cm_media_objects mo on mo.media_object_id = rs.media_object_id
     where rs.review_session_id = p_review_session_id;
    return l_start;
  end session_segment_start;

  function session_segment_end(p_review_session_id in number) return number is
    l_end number;
  begin
    select coalesce(mo.source_end_second, o.end_second, o.start_second + 1)
      into l_end
      from afma_cm_review_sessions rs
      join afma_cm_observations o on o.observation_id = rs.observation_id
      left join afma_cm_media_objects mo on mo.media_object_id = rs.media_object_id
     where rs.review_session_id = p_review_session_id;
    return l_end;
  end session_segment_end;

  procedure validate_session(p_review_session_id in number) is
    l_count number;
  begin
    select count(*) into l_count
      from afma_cm_review_sessions
     where review_session_id = p_review_session_id
       and session_status <> 'CLOSED';
    if l_count = 0 then
      raise_application_error(-20400, 'The Evidence Review Studio session is not available.');
    end if;
  end validate_session;

  procedure get_segment_media(
    p_review_session_id   in number,
    p_filename            out varchar2,
    p_mime_type           out varchar2,
    p_source_start_second out number,
    p_source_end_second   out number,
    p_content             out nocopy blob
  ) is
  begin
    validate_session(p_review_session_id);
    select mo.original_filename,
           mo.mime_type,
           mo.source_start_second,
           mo.source_end_second,
           mo.content_blob
      into p_filename,
           p_mime_type,
           p_source_start_second,
           p_source_end_second,
           p_content
      from afma_cm_review_sessions rs
      join afma_cm_media_objects mo on mo.media_object_id = rs.media_object_id
     where rs.review_session_id = p_review_session_id
       and mo.content_blob is not null
       and dbms_lob.getlength(mo.content_blob) > 0;
  exception
    when no_data_found then
      raise_application_error(-20408, 'The stored bounded segment is no longer available for playback.');
  end get_segment_media;

  function open_session(p_observation_id in number) return number is
    l_session_id number;
    l_submission_id number;
    l_media_object_id number;
    l_start number;
    l_end number;
    l_taxon varchar2(500);
    l_count number;
  begin
    select o.start_second, coalesce(o.end_second, o.start_second + 1),
           coalesce(t.common_name, t.scientific_name, o.ai_taxon_text, 'Unresolved taxon'),
           o.ai_count,
           (select max(vs.submission_id)
              from afma_cm_video_submissions vs
             where vs.analysis_run_id = o.analysis_run_id
               and vs.processing_status <> 'DELETED')
      into l_start, l_end, l_taxon, l_count, l_submission_id
      from afma_cm_observations o
      left join csiro_caab_taxa t on t.spcode = coalesce(o.reviewed_spcode, o.ai_spcode)
     where o.observation_id = p_observation_id
       and o.superseded_at is null;

    if l_submission_id is not null then
      select max(mo.media_object_id) keep (
               dense_rank first order by
                 case when mo.content_blob is not null and dbms_lob.getlength(mo.content_blob) > 0 then 0 else 1 end,
                 mo.source_start_second desc,
                 mo.media_object_id desc)
        into l_media_object_id
        from afma_cm_media_objects mo
       where mo.submission_id = l_submission_id
         and mo.object_key like 'ANALYSIS_SEG_%'
         and l_start >= mo.source_start_second
         and l_start < mo.source_end_second;
    end if;

    begin
      select review_session_id
        into l_session_id
        from afma_cm_review_sessions
       where observation_id = p_observation_id
         and session_status in ('OPEN','ANALYSING','PROPOSAL_READY','ERROR')
       order by updated_at desc
       fetch first 1 row only;
      update afma_cm_review_sessions
         set submission_id = l_submission_id,
             media_object_id = coalesce(l_media_object_id, media_object_id),
             updated_at = systimestamp,
             updated_by = actor_name
       where review_session_id = l_session_id;
    exception
      when no_data_found then
        insert into afma_cm_review_sessions (
          observation_id, submission_id, media_object_id
        ) values (
          p_observation_id, l_submission_id, l_media_object_id
        ) returning review_session_id into l_session_id;

        insert into afma_cm_review_messages (
          review_session_id, message_role, message_text, time_start_second, time_end_second
        ) values (
          l_session_id, 'AGENT',
          'I have opened a review of the current proposal: ' || l_taxon || ', count ' || l_count ||
          ', at ' || fmt_second(l_start) || '–' || fmt_second(l_end) || '. Tell me what appears wrong or identify useful timestamps. I can inspect the stored visual-only segment, compare the result with earlier evidence runs, search CAAB and prepare a corrected proposal. Nothing is accepted until an officer explicitly applies the proposed finding.',
          l_start, l_end
        );
    end;
    commit;
    return l_session_id;
  exception
    when no_data_found then
      raise_application_error(-20401, 'The selected current observation could not be opened for review.');
  end open_session;

  function begin_tool_run(
    p_review_session_id in number,
    p_tool_name         in varchar2,
    p_arguments_json    in clob
  ) return number is
    l_tool_run_id number;
  begin
    validate_session(p_review_session_id);
    insert into afma_cm_review_tool_runs (
      review_session_id, tool_name, arguments_json
    ) values (
      p_review_session_id, p_tool_name, p_arguments_json
    ) returning tool_run_id into l_tool_run_id;
    commit;
    return l_tool_run_id;
  end begin_tool_run;

  procedure finish_tool_run(
    p_tool_run_id     in number,
    p_result_json     in clob,
    p_evidence_run_id in number default null
  ) is
  begin
    update afma_cm_review_tool_runs
       set run_status = 'COMPLETE', result_json = p_result_json,
           evidence_run_id = p_evidence_run_id, completed_at = systimestamp
     where tool_run_id = p_tool_run_id;
    commit;
  end finish_tool_run;

  procedure fail_tool_run(p_tool_run_id in number, p_error in varchar2) is
  begin
    update afma_cm_review_tool_runs
       set run_status = 'FAILED', error_message = substr(p_error, 1, 4000), completed_at = systimestamp
     where tool_run_id = p_tool_run_id;
    commit;
  end fail_tool_run;

  procedure tool_get_review_context(
    p_param  in            apex_ai.t_tool_exec_param,
    p_result in out nocopy apex_ai.t_tool_exec_result
  ) is
    l_session_id number := p_param.args_json.get_number('review_session_id');
    l_tool_run_id number;
    l_result clob;
  begin
    l_tool_run_id := begin_tool_run(l_session_id, 'get_review_context', p_param.args);
    select json_object(
             'reviewSessionId' value rs.review_session_id,
             'observationId' value o.observation_id,
             'observationType' value o.observation_type,
             'currentTaxonText' value coalesce(t.common_name, t.scientific_name, o.ai_taxon_text),
             'currentSpcode' value coalesce(o.reviewed_spcode, o.ai_spcode),
             'currentCount' value coalesce(o.reviewed_count, o.ai_count),
             'eventStartSecond' value o.start_second,
             'eventEndSecond' value o.end_second,
             'segmentStartSecond' value coalesce(mo.source_start_second, o.start_second),
             'segmentEndSecond' value coalesce(mo.source_end_second, o.end_second),
             'reviewerStatus' value o.reviewer_status,
             'evidenceText' value o.evidence_text,
             'uncertainty' value o.ai_uncertainty,
             'storedSegmentAvailable' value case when mo.content_blob is not null and dbms_lob.getlength(mo.content_blob) > 0 then 'true' else 'false' end format json
             returning clob)
      into l_result
      from afma_cm_review_sessions rs
      join afma_cm_observations o on o.observation_id = rs.observation_id
      left join afma_cm_media_objects mo on mo.media_object_id = rs.media_object_id
      left join csiro_caab_taxa t on t.spcode = coalesce(o.reviewed_spcode, o.ai_spcode)
     where rs.review_session_id = l_session_id;
    finish_tool_run(l_tool_run_id, l_result);
    p_result.result := l_result;
  exception
    when others then
      if l_tool_run_id is not null then fail_tool_run(l_tool_run_id, sqlerrm); end if;
      raise;
  end tool_get_review_context;

  procedure tool_inspect_stored_segment(
    p_param  in            apex_ai.t_tool_exec_param,
    p_result in out nocopy apex_ai.t_tool_exec_result
  ) is
    l_session_id number := p_param.args_json.get_number('review_session_id');
    l_focus_start number := p_param.args_json.get_number('focus_start_second');
    l_focus_end number := p_param.args_json.get_number('focus_end_second');
    l_question varchar2(1000) := p_param.args_json.get_string('inspection_question');
    l_submission_id number;
    l_media_object_id number;
    l_analysis_run_id number;
    l_original_observation_id number;
    l_segment_start number;
    l_segment_end number;
    l_evidence_run_id number;
    l_new_observation_id number;
    l_tool_run_id number;
    l_instruction varchar2(1000);
    l_result clob;
  begin
    l_tool_run_id := begin_tool_run(l_session_id, 'inspect_stored_segment', p_param.args);
    select rs.submission_id, rs.media_object_id, rs.observation_id,
           o.analysis_run_id, coalesce(mo.source_start_second, o.start_second),
           coalesce(mo.source_end_second, o.end_second)
      into l_submission_id, l_media_object_id, l_original_observation_id,
           l_analysis_run_id, l_segment_start, l_segment_end
      from afma_cm_review_sessions rs
      join afma_cm_observations o on o.observation_id = rs.observation_id
      left join afma_cm_media_objects mo on mo.media_object_id = rs.media_object_id
     where rs.review_session_id = l_session_id;

    if l_media_object_id is null then
      raise_application_error(-20402, 'No stored analysis rendition is linked to this review session.');
    end if;
    if l_focus_start is null then l_focus_start := l_segment_start; end if;
    if l_focus_end is null then l_focus_end := l_segment_end; end if;
    if l_focus_start < l_segment_start or l_focus_end > l_segment_end or l_focus_end <= l_focus_start then
      raise_application_error(-20403, 'The requested inspection interval must stay inside the stored segment boundary.');
    end if;

    l_instruction := substr(
      'Evidence Review Studio inspection. Focus especially on source time ' ||
      fmt_second(l_focus_start) || '–' || fmt_second(l_focus_end) || '. ' ||
      'Treat the reviewer question as a hypothesis, not ground truth: ' || trim(l_question) || '. ' ||
      'Count only visibly completed water-to-vessel or water-to-deck landing transitions. Do not extrapolate from crew activity, pole movement, claimed catch rate, narration, title text or accumulated fish already visible on deck. Cite temporal anchors and state uncertainty.',
      1, 1000);

    update afma_cm_review_sessions
       set session_status = 'ANALYSING', updated_at = systimestamp, updated_by = actor_name
     where review_session_id = l_session_id;
    commit;

    afma_cm_evidence_api.rerun_segment(
      p_submission_id        => l_submission_id,
      p_media_object_id      => l_media_object_id,
      p_reviewer_instruction => l_instruction
    );

    select max(evidence_run_id)
      into l_evidence_run_id
      from afma_cm_evidence_runs
     where submission_id = l_submission_id
       and media_object_id = l_media_object_id
       and run_purpose = 'SEGMENT_REANALYSIS'
       and run_status = 'COMPLETE';

    select min(observation_id) keep (
             dense_rank first order by abs(start_second - l_focus_start), observation_id)
      into l_new_observation_id
      from afma_cm_observations
     where analysis_run_id = l_analysis_run_id
       and evidence_run_id = l_evidence_run_id
       and superseded_at is null;

    if l_new_observation_id is not null then
      update afma_cm_review_sessions
         set observation_id = l_new_observation_id
       where review_session_id = l_session_id;
    end if;

    select json_object(
             'evidenceRunId' value l_evidence_run_id,
             'reviewSessionId' value l_session_id,
             'focusStartSecond' value l_focus_start,
             'focusEndSecond' value l_focus_end,
             'publishedProposals' value (
               select json_arrayagg(
                        json_object(
                          'observationId' value o.observation_id,
                          'startSecond' value o.start_second,
                          'endSecond' value o.end_second,
                          'taxonText' value coalesce(t.common_name, t.scientific_name, o.ai_taxon_text),
                          'spcode' value o.ai_spcode,
                          'count' value o.ai_count,
                          'confidence' value o.ai_confidence,
                          'evidence' value o.evidence_text,
                          'uncertainty' value o.ai_uncertainty
                          returning clob)
                        returning clob)
                 from afma_cm_observations o
                 left join csiro_caab_taxa t on t.spcode = o.ai_spcode
                where o.evidence_run_id = l_evidence_run_id
                  and o.superseded_at is null
             ) format json
             returning clob)
      into l_result
      from dual;

    update afma_cm_review_sessions
       set session_status = 'OPEN', updated_at = systimestamp, updated_by = actor_name
     where review_session_id = l_session_id;
    finish_tool_run(l_tool_run_id, l_result, l_evidence_run_id);
    p_result.result := l_result;
  exception
    when others then
      update afma_cm_review_sessions
         set session_status = 'ERROR', updated_at = systimestamp, updated_by = actor_name
       where review_session_id = l_session_id;
      commit;
      if l_tool_run_id is not null then fail_tool_run(l_tool_run_id, sqlerrm); end if;
      raise;
  end tool_inspect_stored_segment;

  procedure tool_lookup_caab_candidates(
    p_param  in            apex_ai.t_tool_exec_param,
    p_result in out nocopy apex_ai.t_tool_exec_result
  ) is
    l_session_id number := p_param.args_json.get_number('review_session_id');
    l_query varchar2(300) := trim(p_param.args_json.get_string('query_text'));
    l_tool_run_id number;
    l_result clob;
  begin
    l_tool_run_id := begin_tool_run(l_session_id, 'lookup_caab_candidates', p_param.args);
    select json_object(
             'query' value l_query,
             'candidates' value coalesce((
               select json_arrayagg(
                        json_object(
                          'spcode' value spcode,
                          'commonName' value common_name,
                          'scientificName' value scientific_name
                          returning clob)
                        returning clob)
                 from (
                   select distinct t.spcode, t.common_name, t.scientific_name
                     from csiro_caab_taxa_active_v t
                    where lower(t.common_name) like '%' || lower(l_query) || '%'
                       or lower(t.scientific_name) like '%' || lower(l_query) || '%'
                       or t.spcode = l_query
                    order by case when lower(t.common_name) = lower(l_query) then 0 else 1 end,
                             t.common_name, t.scientific_name
                    fetch first 12 rows only
                 )
             ), to_clob('[]')) format json
             returning clob)
      into l_result
      from dual;
    finish_tool_run(l_tool_run_id, l_result);
    p_result.result := l_result;
  exception
    when others then
      if l_tool_run_id is not null then fail_tool_run(l_tool_run_id, sqlerrm); end if;
      raise;
  end tool_lookup_caab_candidates;

  procedure tool_create_corrected_proposal(
    p_param  in            apex_ai.t_tool_exec_param,
    p_result in out nocopy apex_ai.t_tool_exec_result
  ) is
    l_session_id number := p_param.args_json.get_number('review_session_id');
    l_taxon_text varchar2(500) := p_param.args_json.get_string('taxon_text');
    l_spcode varchar2(20) := p_param.args_json.get_string('spcode');
    l_count number := p_param.args_json.get_number('count');
    l_start number := p_param.args_json.get_number('start_second');
    l_end number := p_param.args_json.get_number('end_second');
    l_interaction varchar2(40) := upper(coalesce(p_param.args_json.get_string('interaction_class'), 'NOT_APPLICABLE'));
    l_confidence number := p_param.args_json.get_number('confidence');
    l_summary varchar2(4000) := p_param.args_json.get_string('evidence_summary');
    l_segment_start number;
    l_segment_end number;
    l_valid_spcode number;
    l_tool_run_id number;
    l_proposal_id number;
    l_result clob;
  begin
    l_tool_run_id := begin_tool_run(l_session_id, 'create_corrected_proposal', p_param.args);
    l_segment_start := session_segment_start(l_session_id);
    l_segment_end := session_segment_end(l_session_id);
    if l_count < 0 or l_count <> trunc(l_count) then
      raise_application_error(-20404, 'Proposal count must be a non-negative whole number.');
    end if;
    if l_start < l_segment_start or l_end > l_segment_end or l_end <= l_start then
      raise_application_error(-20405, 'Proposal evidence range must stay inside the stored segment.');
    end if;
    if trim(l_summary) is null then
      raise_application_error(-20406, 'Proposal evidence summary is required.');
    end if;
    if trim(l_spcode) is not null then
      select count(*) into l_valid_spcode from csiro_caab_taxa_active_v where spcode = trim(l_spcode);
      if l_valid_spcode = 0 then
        raise_application_error(-20407, 'Proposal CAAB SPCODE is not active.');
      end if;
    end if;

    update afma_cm_review_proposals
       set proposal_status = 'SUPERSEDED', decided_at = systimestamp, decided_by = actor_name
     where review_session_id = l_session_id
       and proposal_status = 'DRAFT';

    insert into afma_cm_review_proposals (
      review_session_id, source_tool_run_id, proposal_source, taxon_text, spcode,
      proposed_count, start_second, end_second, interaction_class, confidence,
      evidence_summary
    ) values (
      l_session_id, l_tool_run_id, 'AGENT', substr(trim(l_taxon_text),1,500), trim(l_spcode),
      l_count, l_start, l_end, l_interaction, l_confidence,
      substr(trim(l_summary),1,4000)
    ) returning review_proposal_id into l_proposal_id;

    update afma_cm_review_sessions
       set session_status = 'PROPOSAL_READY', updated_at = systimestamp, updated_by = actor_name
     where review_session_id = l_session_id;

    select json_object(
             'proposalId' value l_proposal_id,
             'status' value 'DRAFT',
             'message' value 'The corrected finding is ready for officer review. It has not changed the reviewed observation.'
             returning clob)
      into l_result from dual;
    finish_tool_run(l_tool_run_id, l_result);
    p_result.result := l_result;
  exception
    when others then
      if l_tool_run_id is not null then fail_tool_run(l_tool_run_id, sqlerrm); end if;
      raise;
  end tool_create_corrected_proposal;


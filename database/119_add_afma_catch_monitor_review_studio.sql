      ),
      apex_ai.t_tool(
        name => 'inspect_stored_segment',
        description => 'Runs a fresh Gemini Pro visual analysis of the stored bounded segment, with special attention to a reviewer-marked interval and question. This is expensive and should be used only when visual reinspection is needed.',
        parameters => apex_ai.t_tool_parameters(
          apex_ai.t_tool_parameter(name=>'review_session_id', description=>'Exact numeric review session id.', data_type=>apex_ai.c_tool_param_type_number),
          apex_ai.t_tool_parameter(name=>'focus_start_second', description=>'Absolute source-video start second inside the stored segment.', data_type=>apex_ai.c_tool_param_type_number),

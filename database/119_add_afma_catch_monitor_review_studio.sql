  procedure accept_proposal(
    p_review_session_id  in number,
    p_review_proposal_id in number default null,
    p_taxon_text         in varchar2 default null,
    p_spcode             in varchar2 default null,
    p_count              in number,
    p_start_second       in number,
    p_end_second         in number,
    p_interaction_class  in varchar2 default 'NOT_APPLICABLE',
    p_reviewer_note      in varchar2 default null
  ) is
    l_observation_id number;
    l_trip_id number;
    l_proposal_id number := p_review_proposal_id;
    l_spcode varchar2(20) := trim(p_spcode);
    l_valid number;
    l_source varchar2(30) := 'AGENT';
  begin
    validate_session(p_review_session_id);
    if p_count < 0 or p_count <> trunc(p_count) then
      raise_application_error(-20410, 'Officer decision count must be a non-negative whole number.');
    end if;
    if p_start_second < session_segment_start(p_review_session_id) or
       p_end_second > session_segment_end(p_review_session_id) or
       p_end_second <= p_start_second then
      raise_application_error(-20411, 'Officer evidence range must stay inside the displayed segment.');
    end if;
    if l_spcode is not null then
      select count(*) into l_valid from csiro_caab_taxa_active_v where spcode = l_spcode;
      if l_valid = 0 then raise_application_error(-20412, 'Enter an active CAAB SPCODE or leave it unresolved.'); end if;
    end if;

    select rs.observation_id, ar.trip_id
      into l_observation_id, l_trip_id
      from afma_cm_review_sessions rs
      join afma_cm_observations o on o.observation_id = rs.observation_id
      join afma_cm_analysis_runs ar on ar.analysis_run_id = o.analysis_run_id
     where rs.review_session_id = p_review_session_id;

    if l_proposal_id is null then
      l_source := 'OFFICER_EDIT';
      insert into afma_cm_review_proposals (
        review_session_id, proposal_source, taxon_text, spcode, proposed_count,
        start_second, end_second, interaction_class, evidence_summary
      ) values (
        p_review_session_id, l_source, substr(trim(p_taxon_text),1,500), l_spcode, p_count,
        p_start_second, p_end_second, upper(coalesce(trim(p_interaction_class),'NOT_APPLICABLE')),
        substr(coalesce(trim(p_reviewer_note),'Officer edited the structured finding in the Evidence Review Studio.'),1,4000)
      ) returning review_proposal_id into l_proposal_id;
    else
      update afma_cm_review_proposals
         set taxon_text = substr(trim(p_taxon_text),1,500), spcode = l_spcode,
             proposed_count = p_count, start_second = p_start_second, end_second = p_end_second,
             interaction_class = upper(coalesce(trim(p_interaction_class),'NOT_APPLICABLE')),
             evidence_summary = case when trim(p_reviewer_note) is not null then substr(trim(p_reviewer_note),1,4000) else evidence_summary end
       where review_proposal_id = l_proposal_id
         and review_session_id = p_review_session_id
         and proposal_status = 'DRAFT';
      if sql%rowcount = 0 then raise_application_error(-20413, 'The selected draft proposal is no longer available.'); end if;
    end if;

    update afma_cm_observations
       set start_second = p_start_second,
           end_second = p_end_second
     where observation_id = l_observation_id;

    afma_cm_api.review_observation(
      p_trip_id                    => l_trip_id,
      p_observation_id             => l_observation_id,
      p_reviewer_status            => 'CORRECTED',
      p_reviewed_spcode            => l_spcode,
      p_reviewed_count             => p_count,
      p_reviewed_interaction_class => upper(coalesce(trim(p_interaction_class),'NOT_APPLICABLE')),
      p_reviewer_notes             => substr('Evidence Review Studio session #' || p_review_session_id ||
                                               ', proposal #' || l_proposal_id || '. ' || trim(p_reviewer_note),1,2000)
    );

    update afma_cm_review_proposals
       set proposal_status = case when review_proposal_id = l_proposal_id then 'ACCEPTED' else 'SUPERSEDED' end,
           decided_at = systimestamp, decided_by = actor_name
     where review_session_id = p_review_session_id
       and proposal_status = 'DRAFT';
    update afma_cm_review_sessions
       set session_status = 'ACCEPTED', accepted_at = systimestamp, accepted_by = actor_name,
           updated_at = systimestamp, updated_by = actor_name
     where review_session_id = p_review_session_id;
    insert into afma_cm_review_messages (
      review_session_id, message_role, message_text, time_start_second, time_end_second
    ) values (
      p_review_session_id, 'SYSTEM',
      'Officer accepted corrected finding proposal #' || l_proposal_id || '. Species/CAAB, count, classification and evidence range were written to observation #' || l_observation_id || '.',
      p_start_second, p_end_second
    );
    commit;
  end accept_proposal;

  procedure escalate_session(
    p_review_session_id in number,
    p_reviewer_note     in varchar2 default null
  ) is
    l_observation_id number;
    l_trip_id number;
  begin
    validate_session(p_review_session_id);
